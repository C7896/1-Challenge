/**
 * The full challenge library.
 *
 * Grouped by theme so the seeder can interleave them, which keeps a user from
 * getting thirty kindness tasks in a row. Every entry is one small thing a
 * person can finish in a single day.
 *
 * House rules for adding more:
 *   - Start with a verb. It is an instruction, not a suggestion.
 *   - Keep it under 95 characters. Longer text overflows the challenge card.
 *   - One action per challenge. If it needs an "and", it is probably two.
 *   - No em dashes anywhere.
 *   - It has to be doable today, for free, by someone with an ordinary day.
 *
 * Run `node scripts/check-challenges.mjs` after editing to validate.
 */

