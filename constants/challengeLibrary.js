// Interleaved so consecutive days rotate through themes rather than
// serving thirty kindness tasks in a row.
const GROUPS = [
  OUTWARD_STRANGERS,
  RELATIONSHIPS,
  BODY_HEALTH,
  GRATITUDE,
  MIND_LEARNING,
  COMMUNITY_ENVIRONMENT,
  COURAGE_GROWTH,
  ATTENTION_DIGITAL,
  GENEROSITY,
  REFLECTION,
];

function interleave(groups) {
  const out = [];
  const longest = Math.max(...groups.map((g) => g.length));
  for (let i = 0; i < longest; i++) {
    for (const group of groups) {
      if (i < group.length) {
        out.push(group[i]);
      }
    }
  }
  return out;
}

export const CHALLENGE_LIBRARY = interleave(GROUPS);

